import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { homedir } from 'node:os';
import { resolve } from 'node:path';
const require = createRequire(import.meta.url);
const runtime = process.env.PLAYWRIGHT_MODULE || resolve(homedir(), '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const { chromium } = require(runtime);
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce'});
try {
  await page.goto(process.env.SITE_URL || 'http://127.0.0.1:4173');
  await page.locator('#menu-toggle').click();
  assert.equal(await page.locator('#menu-toggle').getAttribute('aria-expanded'), 'true', 'Menu deve abrir');
  assert.equal(await page.locator('#mobile-menu').isVisible(), true);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#menu-toggle').getAttribute('aria-expanded'), 'false');
  assert.equal(await page.locator('#menu-toggle').evaluate(el=>document.activeElement===el),true,'Foco volta ao menu');
  const contact = page.locator('.hero-panel [data-contact]');
  const target = new URL(await contact.getAttribute('href'));
  assert.equal(target.pathname,'/5521967643628');
  assert.ok(target.searchParams.get('text').includes('orçamento'));
  assert.equal(await contact.getAttribute('target'),'_blank');
  assert.equal(await page.locator('.service-card').count(),5);
  assert.equal(await page.locator('#conteudos').count(),0);
  // Exercise real click/popup without contacting WhatsApp or sending a message.
  await page.context().route('https://wa.me/**',route=>route.fulfill({status:200,body:'WhatsApp target checked locally'}));
  const popupPromise=page.waitForEvent('popup');
  await contact.click();
  const popup=await popupPromise;await popup.waitForLoadState();
  assert.equal(new URL(popup.url()).pathname,'/5521967643628');await popup.close();
  await page.locator('#menu-toggle').click();
  const mobilePopupPromise=page.waitForEvent('popup');
  await page.locator('#mobile-menu [data-contact]').click();
  const mobilePopup=await mobilePopupPromise;await mobilePopup.close();
  assert.equal(await page.locator('#mobile-menu').isVisible(),false,'CTA externa fecha o menu sem erro de seletor');
  const faq = page.locator('[data-accordion]');
  await faq.nth(1).click();
  assert.equal(await faq.nth(1).getAttribute('aria-expanded'),'true');
  assert.equal(await faq.nth(0).getAttribute('aria-expanded'),'false');
  const gallery = page.locator('[data-gallery]').first();
  await gallery.click();
  assert.equal(await page.locator('#gallery-dialog').isVisible(),true);
  await page.keyboard.press('Escape');
  assert.equal(await gallery.evaluate(el=>document.activeElement===el),true);
  const carousel = page.locator('[data-carousel]').first();
  const track = carousel.locator('[data-track]');
  const choices = carousel.locator('[data-service-index]');
  await choices.nth(4).click();
  await page.waitForFunction(()=>document.querySelector('[data-service-index="4"]').getAttribute('aria-pressed')==='true');
  assert.match(await carousel.locator('[data-carousel-position]').innerText(),/^5 de 5 · Vitrines/);
  const chosenPosition = await track.evaluate(el=>el.scrollLeft);
  assert.ok(chosenPosition>0,'Índice leva diretamente ao último serviço');
  await choices.first().focus();await page.keyboard.press('Enter');
  await page.waitForFunction(()=>document.querySelector('[data-service-index="0"]').getAttribute('aria-pressed')==='true');
  assert.match(await carousel.locator('[data-carousel-position]').innerText(),/^1 de 5/);
  await carousel.locator('[data-next]').click();
  assert.ok(await track.evaluate(el=>el.scrollLeft)>0,'Próximo move a faixa');
  await track.focus();
  await page.keyboard.press('End');
  await page.waitForFunction(()=>document.querySelector('[data-carousel] [data-next]').disabled);
  assert.equal(await carousel.locator('[data-next]').isDisabled(),true,'Fim desabilita seta');
  await page.keyboard.press('Home');
  await page.waitForFunction(()=>document.querySelector('[data-carousel] [data-prev]').disabled);
  assert.equal(await carousel.locator('[data-prev]').isDisabled(),true,'Início desabilita seta');
  const faqBeforeHelp = await page.locator('#duvidas').evaluate(el=>el.querySelector('.faq-list').getBoundingClientRect().top < el.querySelector('.faq-support').getBoundingClientRect().top);
  assert.equal(faqBeforeHelp,true,'Perguntas precedem card de ajuda no mobile');
  const contactBeforeMenu = await page.locator('.footer-grid').evaluate(el=>el.querySelector('.footer-contact').getBoundingClientRect().top < el.querySelector('nav').getBoundingClientRect().top);
  assert.equal(contactBeforeMenu,true,'Contato precede menus no mobile');
  console.log('Interações passaram: menu/Escape/foco; contato; FAQ exclusivo; galeria/Escape/foco; carrossel/setas/teclado/finais.');
} finally { await browser.close(); }
